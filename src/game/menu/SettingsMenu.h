#pragma once

#include <optional>
#include <utility>

#include "engine/assets/StringTable.h"
#include "engine/core/Types.h"
#include "engine/render/RenderTypes.h"

#include "game/config/GameConfig.h"
#include "game/mechanics/MechanicCatalog.h"
#include "game/menu/ControlSettings.h"
#include "game/menu/LiveSettings.h"
#include "game/menu/VideoSettings.h"
#include "game/widgets/OptionMenu.h"

namespace gdl::game {

/** Shared title/pause settings with transactional edits. */
class SettingsMenu {
public:
    enum class Page : u8 {
        Root,
        Audio,
        Game,
        Compass,
        Difficulty,
        Multiplayer,
        Graphics,
        Controls,
        Combat
    };
    enum class Scope : u8 { Title, Tower, Level };
    /** `settings` saves and previews the edits and says which displays the Video page offers
     * and which graphics API draws now: the page offers the other from the title alone, and
     * says a restart is needed while the choice differs from it. Without it nothing is saved
     * or previewed, no display is offered and Vulkan is taken to be drawing. */
    void open(const GameConfig& config, const StringTable* strings, LiveSettings* settings,
              const TextPainter& painter, const MenuScreen& screen, MenuDefinition backdrop,
              Scope scope = Scope::Title);
    /** Test seam: the clock that times the Video page's confirmation; the steady clock until
     * one is set. */
    void setClock(VideoSettings::Clock clock) { m_clock = std::move(clock); }
    /** The mechanics the Game page offers, a switch each after its own; none until told. */
    void setMechanics(const MechanicCatalog* mechanics) { m_mechanics = mechanics; }
    MenuEvent update(const MenuInput& input, s32 ticks);
    /** Optional effects-volume demonstration generated by the latest update. */
    std::string_view audioSample() const { return m_audioSample; }
    void close();
    bool isOpen() const { return m_menu.isOpen(); }
    Page page() const { return m_page; }
    /** Whether the music plays on under the page shown: only under Audio, so that its slider
     * can be heard (options.c 984). */
    [[nodiscard]] bool playsMusic() const { return m_page == Page::Audio; }
    /** Whether the page shown carries the menu's seal, as the root's and Compass's retail
     * records do (8011E390/8011E638, 8011EF60); the other pages have none. */
    [[nodiscard]] bool showsSeal() const { return m_page == Page::Root || m_page == Page::Compass; }
    /** How far in the menu is: the root, a page, or a player's controls within Controls.
     * A scene hears a step back as the depth falls. */
    s32 depth() const;
    const GameConfig& config() const { return m_config; }
    /** The renderer chosen is not the one drawing: it takes effect at the next start. */
    bool restartNeeded() const { return m_config.display.renderer != m_renderer; }
    const OptionMenu& menu() const { return m_menu; }
    OptionMenu& menu() { return m_menu; }
    void draw(Canvas& canvas, const TextPainter& painter, const MenuTextures& textures) const;

private:
    void rebuild(s32 selection = 0);
    /** The row a list page opens on: its current choice, else the first. */
    s32 currentChoice() const;
    /** The code of the row a choice page (Difficulty, Multiplayer, Compass) marks; none for a
     * difficulty it does not know, or on any other page. */
    [[nodiscard]] std::optional<s32> chosen() const;
    void change(s32 direction);
    /** Takes the display the running game offers now, when there is one. */
    void refreshDisplay();
    bool flushAudio();
    void commit(GameConfig next);
    /** The volume the Audio page's slider `row` sets. */
    f32& audioVolume(usize row);
    std::string text(std::string_view id) const;
    /** The mechanic the Game page's row `code` switches, if it is one. */
    const MechanicDescriptor* mechanicOf(s32 code) const;
    std::vector<StringTable::Language> languages() const;
    /** What the chosen language calls itself, else its code. */
    std::string languageName() const;
    OptionMenu m_menu;
    ControlSettings m_controls;
    MenuDefinition m_backdrop;
    const TextPainter* m_painter = nullptr;
    const StringTable* m_strings = nullptr;
    const MechanicCatalog* m_mechanics = nullptr;
    LiveSettings* m_settings = nullptr;
    DisplayOptions m_display;
    std::vector<Extent2D> resolutions() const;
    /** The display the Video page shows: the one chosen, else the one the window is on. */
    s32 shownMonitor() const;
    std::optional<usize> m_audioDrag;
    GameConfig m_config;
    std::string m_notice;
    VideoSettings m_video;
    VideoSettings::Clock m_clock;
    s32 m_countdown = 0;
    MenuScreen m_screen;
    std::optional<Vec2> m_audioPointer;
    bool m_audioDirty = false;
    s32 m_audioSampleTicks = 0;
    bool m_audioSampleMagic = false;
    std::string_view m_audioSample;
    Scope m_scope = Scope::Title;
    GraphicsApi m_renderer = GraphicsApi::Vulkan; ///< the API drawing now
    Page m_page = Page::Root;
    s32 m_windowKey = -1; ///< which page's window the open menu shows
    bool m_confirmVideo = false;
};
} // namespace gdl::game
